"""
24. RLHF PPO Training Loop
Deep Dive Implementation

This file demonstrates the Proximal Policy Optimization (PPO) training loop used
in RLHF (Reinforcement Learning from Human Feedback) to align models like ChatGPT
or Claude. It requires a Base Model (Policy), a Reference Model (for KL Penalty),
a Reward Model (to judge outputs), and a Value Model (to predict expected reward).
"""

import torch
import torch.nn as nn
import torch.nn.functional as F

# ---------------------------------------------------------------------------
# 1. MOCK MODELS FOR DEMONSTRATION
# ---------------------------------------------------------------------------

class MockLLM(nn.Module):
    """A dummy LLM that outputs logits over a tiny vocabulary."""
    def __init__(self, vocab_size=100, embed_dim=16):
        super().__init__()
        self.net = nn.Sequential(
            nn.Linear(embed_dim, 64),
            nn.ReLU(),
            nn.Linear(64, vocab_size)
        )
        
    def forward(self, hidden_states):
        return self.net(hidden_states)

class MockRewardModel(nn.Module):
    """Outputs a single scalar reward per token (or per sequence)."""
    def __init__(self, embed_dim=16):
        super().__init__()
        self.net = nn.Sequential(
            nn.Linear(embed_dim, 32),
            nn.ReLU(),
            nn.Linear(32, 1)
        )
        
    def forward(self, hidden_states):
        return self.net(hidden_states).squeeze(-1)

# ---------------------------------------------------------------------------
# 2. PPO LOSS FUNCTION ALGORITHMS
# ---------------------------------------------------------------------------

def calculate_kl_divergence(logprobs_policy, logprobs_ref):
    """
    Calculates how far the active model has drifted from the reference model.
    We penalize the model if it changes its personality too much to cheat the reward model.
    """
    return logprobs_policy - logprobs_ref

def ppo_step(
    prompts,               # The input context
    responses,             # The text generated by the model
    logprobs_old,          # Log probabilities from the model *before* the update
    logprobs_ref,          # Log probabilities from the frozen reference model
    rewards,               # Scalar score from the Reward Model
    values_old,            # Value predictions from the Value Model
    policy_model,          # The LLM we are training
    value_model,           # The model predicting expected rewards
    optimizer_policy,
    optimizer_value,
    clip_range=0.2,
    kl_beta=0.1
):
    """
    Executes a single step of Proximal Policy Optimization.
    """
    # 1. Forward Pass (Get current predictions)
    logits_new = policy_model(responses) 
    logprobs_new = F.log_softmax(logits_new, dim=-1).max(dim=-1).values # Simplified logprob selection
    values_new = value_model(responses)
    
    # 2. Calculate KL Penalty (Don't drift too far from reference!)
    kl_penalty = calculate_kl_divergence(logprobs_new, logprobs_ref)
    
    # 3. Calculate Advantages (Did this action result in a better reward than we expected?)
    # Advantage = (Actual Reward - KL Penalty) - Expected Value
    # (In reality, we use Generalized Advantage Estimation (GAE) across the sequence length)
    advantages = (rewards - kl_beta * kl_penalty) - values_old.detach()
    
    # Normalize advantages for training stability
    advantages = (advantages - advantages.mean()) / (advantages.std() + 1e-8)
    
    # 4. PPO Policy Loss (The clipped surrogate objective)
    # Ratio of new probability to old probability
    ratio = torch.exp(logprobs_new - logprobs_old)
    
    # Unclipped objective
    pg_loss1 = -advantages * ratio
    
    # Clipped objective (Prevent massive, unstable updates)
    pg_loss2 = -advantages * torch.clamp(ratio, 1.0 - clip_range, 1.0 + clip_range)
    
    # Final Policy Loss (Take the worst-case scenario)
    policy_loss = torch.max(pg_loss1, pg_loss2).mean()
    
    # 5. Value Model Loss (Train the value model to predict rewards better)
    # MSE between predicted values and actual received rewards
    returns = rewards - kl_beta * kl_penalty
    value_loss = F.mse_loss(values_new, returns.detach())
    
    # 6. Backpropagation
    optimizer_policy.zero_grad()
    policy_loss.backward(retain_graph=True)
    optimizer_policy.step()
    
    optimizer_value.zero_grad()
    value_loss.backward()
    optimizer_value.step()
    
    return policy_loss.item(), value_loss.item(), kl_penalty.mean().item()

# ---------------------------------------------------------------------------
# 3. MOCK TRAINING LOOP
# ---------------------------------------------------------------------------

if __name__ == "__main__":
    print("--- 24. RLHF Proximal Policy Optimization (PPO) Loop ---")
    
    batch_size = 4
    seq_len = 10
    embed_dim = 16
    
    # Initialize our 4 required models
    policy_model = MockLLM(embed_dim=embed_dim)
    ref_model = MockLLM(embed_dim=embed_dim) # Frozen copy
    ref_model.eval()
    
    value_model = MockRewardModel(embed_dim=embed_dim)
    reward_model = MockRewardModel(embed_dim=embed_dim) # Frozen judge
    reward_model.eval()
    
    # Optimizers
    opt_policy = torch.optim.Adam(policy_model.parameters(), lr=1e-5)
    opt_value = torch.optim.Adam(value_model.parameters(), lr=1e-5)
    
    # Simulate a generated batch of data (Hidden states representing the tokens)
    dummy_responses = torch.randn(batch_size, seq_len, embed_dim)
    
    # Simulate the "Gathering Data" phase (done with torch.no_grad)
    with torch.no_grad():
        logits_old = policy_model(dummy_responses)
        logprobs_old = F.log_softmax(logits_old, dim=-1).max(dim=-1).values
        
        logits_ref = ref_model(dummy_responses)
        logprobs_ref = F.log_softmax(logits_ref, dim=-1).max(dim=-1).values
        
        rewards = reward_model(dummy_responses)
        values_old = value_model(dummy_responses)
        
    print("Starting PPO Update Step...")
    p_loss, v_loss, kl = ppo_step(
        prompts=None,
        responses=dummy_responses,
        logprobs_old=logprobs_old,
        logprobs_ref=logprobs_ref,
        rewards=rewards,
        values_old=values_old,
        policy_model=policy_model,
        value_model=value_model,
        optimizer_policy=opt_policy,
        optimizer_value=opt_value
    )
    
    print(f"Policy Loss: {p_loss:.4f}")
    print(f"Value Model Loss: {v_loss:.4f}")
    print(f"KL Penalty (Drift from ref): {kl:.4f}")
    print("Success: PPO Step executed, weights updated without collapsing.")
